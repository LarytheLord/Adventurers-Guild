import * as home from '@/lib/home/content';
import { AUDIT_PACKAGES } from '@/lib/audit-offer/content';

describe('home page content', () => {
  const all = JSON.stringify(home);
  const text = all.toLowerCase();

  it('is pure ASCII', () => {
    // eslint-disable-next-line no-control-regex
    expect(/^[\x00-\x7F]*$/.test(all)).toBe(true);
  });

  it('links to every required page', () => {
    for (const href of [
      '/ai-risk-tier',
      '/guides/cert-in-ai-security-auditing-guidelines',
      '/audit',
      '/checklist',
      '/adventurers',
    ]) {
      expect(all).toContain(`"${href}"`);
    }
  });

  it('contact link is the agreed mailto', () => {
    expect(home.HOME_MAILTO).toBe('mailto:abid@guilds.work?subject=Guild%20enquiry');
  });

  it('has the umbrella line', () => {
    expect(home.HOME_UMBRELLA).toBe('We check AI-built work before people rely on it.');
  });

  it('leads with the Launch Check as the featured offer', () => {
    const f = home.HOME_FEATURED_OFFER;
    expect(f.id).toBe('launch-check');
    expect(f.title).toBe('Launch Check');
    expect(f.primary).toEqual({ label: 'Run the free launch self-check', href: '/launch-check' });
    expect(f.secondary).toEqual({ label: expect.any(String), href: '/audit' });
    expect(f.secondary.label.length).toBeGreaterThan(5);
  });

  it('shows the same price as /audit, taken from the audit offer data', () => {
    const check = AUDIT_PACKAGES.find((p) => p.name === 'Check');
    expect(check).toBeDefined();
    expect(home.HOME_FEATURED_OFFER.price).toBe(check!.price);
    expect(home.HOME_FEATURED_OFFER.priceNote).toContain(check!.time);
  });

  it('has exactly three offers in total: the featured Launch Check plus two smaller cards', () => {
    expect(home.HOME_OFFERS).toHaveLength(2);
    expect(1 + home.HOME_OFFERS.length).toBe(3);
    expect(home.HOME_OFFERS.map((o) => o.id)).toEqual(['cert-in', 'indic-ai-qa']);
  });

  it('keeps the other offers as smaller cards, none of them the Launch Check', () => {
    expect(home.HOME_OFFERS.map((o) => o.id)).not.toContain('launch-check');
    expect(home.HOME_OFFERS.map((o) => o.id)).not.toContain('production-check');
    for (const o of home.HOME_OFFERS) {
      expect(o.title.length).toBeGreaterThan(5);
      expect(o.body.length).toBeGreaterThan(20);
      expect(o.primary.href.startsWith('/')).toBe(true);
    }
  });

  it('says plainly that Guild is not a CERT-In empanelled auditor', () => {
    expect(text).toContain('not a cert-in empanelled auditor');
  });

  it('has no user counts, testimonials, logos or invented numbers', () => {
    for (const bad of ['500+', '1000+', 'testimonial', 'trusted by', 'what our clients', 'users', 'logos']) {
      expect(text).not.toContain(bad);
    }
    // no digits at all (mailto excluded; "v0" is a product name; the Launch Check
    // price and turnaround are the figures already published on /audit)
    const check = AUDIT_PACKAGES.find((p) => p.name === 'Check')!;
    const scrubbed = all
      .split(home.HOME_MAILTO).join('')
      .split(check.price).join('')
      .split(check.time).join('')
      .replace(/\bv0\b/g, '');
    expect(scrubbed.match(/\d+/g) ?? []).toEqual([]);
  });

  it('does not mention AI tools that wrote the page', () => {
    // "Cursor" is allowed only as a supported app builder in the offer text ("v0 or Cursor")
    const noTools = text.split('v0 or cursor').join('');
    for (const bad of ['claude', 'chatgpt', 'copilot', 'cursor', 'generated by']) {
      expect(noTools).not.toContain(bad);
    }
  });
});
