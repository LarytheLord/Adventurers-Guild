import * as home from '@/lib/home/content';

describe('home page content', () => {
  const all = JSON.stringify(home);
  const text = all.toLowerCase();

  it('is pure ASCII', () => {
    // eslint-disable-next-line no-control-regex
    expect(/^[\x00-\x7F]*$/.test(all)).toBe(true);
  });

  it('links to every required page', () => {
    for (const href of [
      '/ai-risk-tier',
      '/guides/cert-in-ai-security-auditing-guidelines',
      '/audit',
      '/checklist',
      '/adventurers',
    ]) {
      expect(all).toContain(`"${href}"`);
    }
  });

  it('contact link is the agreed mailto', () => {
    expect(home.HOME_MAILTO).toBe('mailto:abid@guilds.work?subject=Guild%20enquiry');
  });

  it('has exactly three offers, each with a title, text and a primary link', () => {
    expect(home.HOME_OFFERS).toHaveLength(3);
    for (const o of home.HOME_OFFERS) {
      expect(o.title.length).toBeGreaterThan(5);
      expect(o.body.length).toBeGreaterThan(20);
      expect(o.primary.href.startsWith('/')).toBe(true);
    }
  });

  it('says plainly that Guild is not a CERT-In empanelled auditor', () => {
    expect(text).toContain('not a cert-in empanelled auditor');
  });

  it('has no user counts, testimonials, logos or invented numbers', () => {
    for (const bad of ['500+', '1000+', 'testimonial', 'trusted by', 'what our clients', 'users', 'logos']) {
      expect(text).not.toContain(bad);
    }
    // no digits at all (mailto excluded; "v0" is a product name)
    const digits = (all.split(home.HOME_MAILTO).join('').replace(/\bv0\b/g, '').match(/\d+/g) ?? []);
    expect(digits).toEqual([]);
  });

  it('does not mention AI tools that wrote the page', () => {
    // "Cursor" is allowed only as a supported app builder in the offer text ("v0 or Cursor")
    const scrubbed = text.split('v0 or cursor').join('');
    for (const bad of ['claude', 'chatgpt', 'copilot', 'cursor', 'generated by']) {
      expect(scrubbed).not.toContain(bad);
    }
  });
});
