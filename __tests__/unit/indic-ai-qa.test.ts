import { readFileSync } from 'fs';
import { join } from 'path';
import sitemap from '@/app/sitemap';
import { HOME_OFFERS } from '@/lib/home/content';
import { indicQaJsonLd, serializeJsonLd, PUBLIC_PAGES } from '@/lib/seo';
import * as qa from '@/lib/indic-ai-qa/content';

const root = join(__dirname, '..', '..');
const read = (p: string) => readFileSync(join(root, p), 'utf8');
const isAscii = (s: string) => /^[\x00-\x7F]*$/.test(s);

describe('/indic-ai-qa content', () => {
  const all = JSON.stringify(qa);
  const text = all.toLowerCase();

  it('is pure ASCII and has no digits (no prices, counts or dates in the copy)', () => {
    expect(isAscii(all)).toBe(true);
    const withoutMeta = JSON.stringify({ ...qa, INDIC_QA_PUBLISHED: '', INDIC_QA_MAILTO: '', INDIC_QA_CITATION: '' });
    expect(withoutMeta.match(/\d+/g) ?? []).toEqual([]);
  });

  it('covers the seven things we check, in order', () => {
    expect(qa.INDIC_QA_CHECKS.map((c) => c.id)).toEqual([
      'meaning-errors',
      'register-politeness',
      'code-mixing',
      'transliteration',
      'refusals',
      'policy-hallucination',
      'judge-agreement',
    ]);
    for (const c of qa.INDIC_QA_CHECKS) {
      expect(c.title.length).toBeGreaterThan(5);
      expect(c.body.length).toBeGreaterThan(60);
    }
  });

  it('names Hindi, Gujarati and Hinglish', () => {
    for (const w of ['hindi', 'gujarati', 'hinglish']) expect(text).toContain(w);
  });

  it('describes a two-week pilot with a week-one and week-two stage', () => {
    expect(text).toContain('two-week');
    expect(qa.INDIC_QA_PILOT.length).toBeGreaterThanOrEqual(4);
    expect(qa.INDIC_QA_PILOT.map((s) => s.title).join(' ').toLowerCase()).toMatch(/week one/);
    expect(qa.INDIC_QA_PILOT.map((s) => s.title).join(' ').toLowerCase()).toMatch(/week two/);
  });

  it('lists what you get', () => {
    expect(qa.INDIC_QA_DELIVERABLES.length).toBeGreaterThanOrEqual(4);
  });

  it('has no prices, client claims or auditor claims', () => {
    for (const bad of [
      '$', 'inr', 'rupee', 'price', 'pricing', 'per month', 'free trial', 'discount',
      'our clients', 'our customers', 'trusted by', 'testimonial', 'case study', 'we have worked with', 'used by',
      'certified', 'accredited', 'we audit', 'audit certificate',
    ]) {
      expect(text).not.toContain(bad);
    }
  });

  it('says Guild is not a CERT-In empanelled auditor and never claims it is', () => {
    expect(text).toContain('not a cert-in empanelled auditor');
    expect(text).not.toMatch(/(?<!not )a cert-in empanelled auditor/);
  });

  it('does not mention AI tools', () => {
    for (const bad of ['claude', 'chatgpt', 'copilot', 'generated by']) expect(text).not.toContain(bad);
  });

  it('contact is abid@guilds.work', () => {
    expect(qa.INDIC_QA_MAILTO.startsWith('mailto:abid@guilds.work?subject=')).toBe(true);
    expect(text).toContain('abid@guilds.work');
  });

  it('cites PARIKSHA by its arXiv id, and only in the citation block', () => {
    expect(qa.INDIC_QA_CITATION.href).toBe('https://arxiv.org/abs/2406.15053');
    expect(qa.INDIC_QA_CITATION.label).toContain('PARIKSHA');
    const rest = JSON.stringify({ ...qa, INDIC_QA_CITATION: '' }).toLowerCase();
    expect(rest).not.toContain('pariksha');
    expect(rest).not.toContain('2406.15053');
  });
});

describe('/indic-ai-qa JSON-LD', () => {
  const [article, service] = JSON.parse(serializeJsonLd(indicQaJsonLd()));

  it('emits an Article and a Service for the page url', () => {
    expect(article['@type']).toBe('Article');
    expect(service['@type']).toBe('Service');
    expect(article.url).toBe('https://www.guilds.work/indic-ai-qa');
    expect(service.url).toBe('https://www.guilds.work/indic-ai-qa');
    expect(article.headline).toBe(qa.INDIC_QA_TITLE);
    expect(article.datePublished).toBe(qa.INDIC_QA_PUBLISHED);
    expect(service.provider.name).toBe('Guild');
  });

  it('carries no price, offer, rating or review', () => {
    const s = JSON.stringify([article, service]).toLowerCase();
    for (const bad of ['offers', 'price', 'aggregaterating', 'review', 'currency']) expect(s).not.toContain(bad);
  });

  it('cites PARIKSHA in the article', () => {
    expect(article.citation[0].url).toBe('https://arxiv.org/abs/2406.15053');
  });
});

describe('/indic-ai-qa wiring', () => {
  it('is in PUBLIC_PAGES, the sitemap and llms.txt', () => {
    expect(PUBLIC_PAGES.map((p) => p.path)).toContain('/indic-ai-qa');
    expect(sitemap().map((e) => e.url)).toContain('https://www.guilds.work/indic-ai-qa');
    expect(read('public/llms.txt')).toContain('(https://www.guilds.work/indic-ai-qa)');
  });

  it('page file sets metadata and emits the JSON-LD', () => {
    const src = read('app/indic-ai-qa/page.tsx');
    expect(isAscii(src)).toBe(true);
    expect(src).toContain('buildPageMetadata');
    expect(src).toContain('indicQaJsonLd');
    expect(src).toContain('INDIC_QA_MAILTO');
  });

  it('home offers list links to the page', () => {
    const o = HOME_OFFERS.find((x) => x.id === 'indic-ai-qa');
    expect(o).toBeDefined();
    expect(o!.primary.href).toBe('/indic-ai-qa');
  });
});
